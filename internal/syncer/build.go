// Package syncer turns the endpoint records from the central database into a Gatus configuration file.
package syncer

import (
	"bytes"
	"fmt"
	"sort"
	"strings"
	"time"

	"gatusmod/internal/badge"
	"gatusmod/internal/config"
	"gatusmod/internal/probe"
	"gatusmod/internal/store"

	"gopkg.in/yaml.v3"
)

const header = "# Generated by GatusMOD from the central database. Do not edit: changes are overwritten on the next sync.\n"

// previewToken stands in for the external endpoint token where the file is only previewed.
const previewToken = "preview"

// minHeartbeat is the lowest heartbeat interval Gatus accepts.
const minHeartbeat = 10 * time.Second

// coreKeys are written from the table columns, in this order. Other keys come from the `extra` column.
var coreKeys = []string{"name", "group", "url", "method", "interval", "enabled", "conditions"}

// externalExtraKeys are the `extra` settings Gatus supports for external endpoints; others are ignored.
var externalExtraKeys = map[string]bool{"alerts": true, "heartbeat": true, "maintenance-windows": true}

type Problem struct {
	Record  string `json:"record"`
	Message string `json:"message"`
}

func (p Problem) String() string { return p.Record + ": " + p.Message }

// Build validates the records and renders them as a Gatus `endpoints:` and `external-endpoints:` file.
// Invalid records are skipped and reported, so one bad row does not break the whole configuration.
func Build(records []store.Record, defaultInterval string) ([]byte, int, []Problem) {
	data, kept, problems := build(records, defaultInterval, previewToken)
	return data, len(kept), problems
}

// build returns the file and the valid records. Records checked by GatusMOD get their effective interval and
// conditions filled in, so Targets does not need the `extra` column.
func build(records []store.Record, defaultInterval, token string) ([]byte, []store.Record, []Problem) {
	docs, kept, problems := buildDocs(records, defaultInterval, token, func(store.Record) string { return "" })
	data, err := render(header, docs[""])
	if err != nil {
		problems = append(problems, Problem{Record: "(all)", Message: err.Error()})
	}
	return data, kept, problems
}

// doc holds the endpoints of one generated file.
type doc struct {
	list, external *yaml.Node
}

// buildDocs validates all records at once, so a duplicate is skipped even when it would go to another file,
// and groups the endpoints by the file fileOf returns.
func buildDocs(records []store.Record, defaultInterval, token string, fileOf func(store.Record) string) (map[string]*doc, []store.Record, []Problem) {
	sorted := append([]store.Record(nil), records...)
	sort.SliceStable(sorted, func(i, j int) bool {
		if sorted[i].Group != sorted[j].Group {
			return sorted[i].Group < sorted[j].Group
		}
		return sorted[i].Name < sorted[j].Name
	})
	var problems []Problem
	var kept []store.Record
	seen := make(map[string]bool)
	docs := map[string]*doc{}
	docFor := func(r store.Record) *doc {
		file := fileOf(r)
		if docs[file] == nil {
			docs[file] = &doc{list: &yaml.Node{Kind: yaml.SequenceNode}, external: &yaml.Node{Kind: yaml.SequenceNode}}
		}
		return docs[file]
	}
	for _, r := range sorted {
		label := describe(r)
		node, resolved, isExternal, err := endpointNode(r, defaultInterval, token)
		if err != nil {
			problems = append(problems, Problem{Record: label, Message: err.Error()})
			continue
		}
		if seen[r.Key()] {
			problems = append(problems, Problem{Record: label, Message: "duplicate group and name, skipped"})
			continue
		}
		seen[r.Key()] = true
		d := docFor(r)
		if isExternal {
			d.external.Content = append(d.external.Content, node)
		} else {
			d.list.Content = append(d.list.Content, node)
		}
		kept = append(kept, resolved)
	}
	return docs, kept, problems
}

// render writes a file with an `endpoints:` list (empty when there are none) and, if any, `external-endpoints:`.
func render(head string, d *doc) ([]byte, error) {
	list := &yaml.Node{Kind: yaml.SequenceNode}
	var external []*yaml.Node
	if d != nil {
		list.Content = d.list.Content
		external = d.external.Content
	}
	if len(list.Content) == 0 {
		list.Style = yaml.FlowStyle
	}
	root := &yaml.Node{Kind: yaml.MappingNode, Content: []*yaml.Node{scalar("endpoints"), list}}
	if len(external) > 0 {
		root.Content = append(root.Content, scalar("external-endpoints"), &yaml.Node{Kind: yaml.SequenceNode, Content: external})
	}
	var buf bytes.Buffer
	buf.WriteString(head)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	err := enc.Encode(root)
	_ = enc.Close()
	return buf.Bytes(), err
}

// Targets returns the endpoints GatusMOD checks itself (or receives pushes for), from records returned by build.
func Targets(records []store.Record) []probe.Target {
	var out []probe.Target
	for _, r := range records {
		if !config.IsProbeURL(r.URL) || r.Disabled {
			continue
		}
		interval, _ := time.ParseDuration(r.Interval)
		out = append(out, probe.Target{
			Key: badge.Key(r.Group, r.Name), Group: r.Group, Name: r.Name, URL: r.URL,
			Interval: interval, Conditions: splitConditions(r.Conditions),
		})
	}
	return out
}

func describe(r store.Record) string {
	name := r.Name
	if name == "" {
		name = "(no name)"
	}
	if r.Group != "" {
		name = r.Group + "/" + name
	}
	if r.ID != "" {
		name += " [id " + r.ID + "]"
	}
	if r.SourceName != "" {
		name = r.SourceName + ": " + name
	}
	return name
}

func endpointNode(r store.Record, defaultInterval, token string) (*yaml.Node, store.Record, bool, error) {
	extra := map[string]any{}
	if strings.TrimSpace(r.Extra) != "" {
		if err := yaml.Unmarshal([]byte(r.Extra), &extra); err != nil {
			return nil, r, false, fmt.Errorf("extra is not a valid YAML mapping: %v", err)
		}
		if extra == nil {
			extra = map[string]any{}
		}
	}
	values := map[string]any{}
	set := func(key string, value any, empty bool) {
		if !empty {
			values[key] = value
		} else if v, ok := extra[key]; ok {
			values[key] = v
		}
		delete(extra, key)
	}
	set("name", r.Name, r.Name == "")
	set("group", r.Group, r.Group == "")
	set("url", r.URL, r.URL == "")
	method := strings.ToUpper(r.Method)
	set("method", method, method == "")
	interval := r.Interval
	if interval == "" {
		if v, ok := extra["interval"]; ok {
			interval = fmt.Sprint(v)
		} else {
			interval = defaultInterval
		}
	}
	set("interval", interval, interval == "")
	set("enabled", false, !r.Disabled)
	conditions := splitConditions(r.Conditions)
	set("conditions", conditions, len(conditions) == 0)

	if s, _ := values["name"].(string); strings.TrimSpace(s) == "" {
		return nil, r, false, fmt.Errorf("name is required")
	}
	rawURL, _ := values["url"].(string)
	if strings.TrimSpace(rawURL) == "" {
		return nil, r, false, fmt.Errorf("url is required")
	}
	if v, ok := values["interval"]; ok {
		if d, err := time.ParseDuration(fmt.Sprint(v)); err != nil || d <= 0 {
			return nil, r, false, fmt.Errorf("interval %q is not a valid duration (examples: 30s, 5m, 1h)", fmt.Sprint(v))
		}
	}
	if config.IsProbeURL(rawURL) {
		node, resolved, err := externalNode(r, values, extra, token)
		return node, resolved, true, err
	}
	if c, ok := values["conditions"]; !ok || isEmptyList(c) {
		return nil, r, false, fmt.Errorf("at least one condition is required")
	}

	node := &yaml.Node{Kind: yaml.MappingNode}
	add := func(key string, value any) error {
		var v yaml.Node
		if err := v.Encode(value); err != nil {
			return fmt.Errorf("%s: %v", key, err)
		}
		node.Content = append(node.Content, scalar(key), &v)
		return nil
	}
	for _, key := range coreKeys {
		if v, ok := values[key]; ok {
			if err := add(key, v); err != nil {
				return nil, r, false, err
			}
		}
	}
	for _, k := range sortedKeys(extra) {
		if err := add(k, extra[k]); err != nil {
			return nil, r, false, err
		}
	}
	return node, r, false, nil
}

// externalNode renders an endpoint GatusMOD checks itself. Gatus only gets name, group, token and heartbeat:
// the URL (which may hold credentials) and the conditions stay in GatusMOD. Active probes get a heartbeat of
// twice their interval, so Gatus marks them down when GatusMOD stops reporting; push endpoints one interval.
func externalNode(r store.Record, values, extra map[string]any, token string) (*yaml.Node, store.Record, error) {
	rawURL := values["url"].(string)
	interval := config.FallbackInterval
	if v, ok := values["interval"]; ok {
		interval, _ = time.ParseDuration(fmt.Sprint(v))
	}
	var conditions []string
	if c, ok := values["conditions"]; ok {
		conditions = toStrings(c)
	}
	if err := probe.Validate(rawURL, conditions); err != nil {
		return nil, r, err
	}
	heartbeat := interval
	if config.SchemeType(rawURL) != config.TypePush {
		heartbeat = 2 * interval
	}
	if heartbeat < minHeartbeat {
		heartbeat = minHeartbeat
	}

	node := &yaml.Node{Kind: yaml.MappingNode}
	add := func(key string, value any) error {
		var v yaml.Node
		if err := v.Encode(value); err != nil {
			return fmt.Errorf("%s: %v", key, err)
		}
		node.Content = append(node.Content, scalar(key), &v)
		return nil
	}
	for _, key := range []string{"name", "group", "enabled"} {
		if v, ok := values[key]; ok {
			if err := add(key, v); err != nil {
				return nil, r, err
			}
		}
	}
	if err := add("token", token); err != nil {
		return nil, r, err
	}
	if _, ok := extra["heartbeat"]; !ok {
		if err := add("heartbeat", map[string]string{"interval": heartbeat.String()}); err != nil {
			return nil, r, err
		}
	}
	for _, k := range sortedKeys(extra) {
		if externalExtraKeys[k] {
			if err := add(k, extra[k]); err != nil {
				return nil, r, err
			}
		}
	}
	resolved := r
	resolved.URL = rawURL
	resolved.Interval = interval.String()
	resolved.Conditions = strings.Join(conditions, "\n")
	return node, resolved, nil
}

// hasEndpoints reports whether any of the files has a regular endpoint; external endpoints do not count for Gatus.
func hasEndpoints(docs map[string]*doc) bool {
	for _, d := range docs {
		if len(d.list.Content) > 0 {
			return true
		}
	}
	return false
}

// placeholderNode is a disabled endpoint for a configuration with only external endpoints: Gatus rejects a
// configuration without endpoints, and stops serving when it reloads one. A disabled endpoint is never checked or shown.
func placeholderNode() *yaml.Node {
	var n yaml.Node
	_ = n.Encode(struct {
		Name       string   `yaml:"name"`
		Group      string   `yaml:"group"`
		URL        string   `yaml:"url"`
		Enabled    bool     `yaml:"enabled"`
		Conditions []string `yaml:"conditions"`
	}{"placeholder", "gatusmod", "http://127.0.0.1", false, []string{"[CONNECTED] == true"}})
	return &n
}

func sortedKeys(m map[string]any) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func toStrings(v any) []string {
	switch t := v.(type) {
	case []string:
		return t
	case []any:
		out := make([]string, 0, len(t))
		for _, item := range t {
			out = append(out, fmt.Sprint(item))
		}
		return out
	case string:
		return splitConditions(t)
	}
	return nil
}

func splitConditions(s string) []string {
	var out []string
	for _, line := range strings.Split(strings.ReplaceAll(s, "\r\n", "\n"), "\n") {
		line = strings.TrimSpace(line)
		line = strings.TrimSpace(strings.TrimPrefix(line, "- "))
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if len(line) >= 2 && line[0] == '"' && line[len(line)-1] == '"' {
			line = line[1 : len(line)-1]
		}
		out = append(out, line)
	}
	return out
}

func isEmptyList(v any) bool {
	l, ok := v.([]any)
	if ok {
		return len(l) == 0
	}
	s, ok := v.([]string)
	return ok && len(s) == 0
}

func scalar(s string) *yaml.Node { return &yaml.Node{Kind: yaml.ScalarNode, Value: s} }
