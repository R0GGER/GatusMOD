func TestSyncOnce_WritesOnlyOnChange(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		_, _ = w.Write([]byte(`{"list":[{"Id":1,"name":"a","url":"https://a","conditions":"[STATUS] == 200"}],"pageInfo":{"isLastPage":true}}`))
	}))
	defer srv.Close()
	dir := t.TempDir()
	cfg := &config.Config{Path: dir, Imports: []config.Import{config.FromDatabase(&config.Database{Provider: "nocodb", URL: srv.URL, TableID: "t", SyncInterval: time.Minute})}}
	s := New(func() *config.Config { return cfg })
	if err := s.SyncOnce(context.Background()); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(dir, config.DefaultOutputFile)
	info1, err := os.Stat(path)
	if err != nil {
		t.Fatal(err)
	}
	firstWrite := s.Status().LastWrite
	time.Sleep(20 * time.Millisecond)
	if err := s.SyncOnce(context.Background()); err != nil {
		t.Fatal(err)
	}
	info2, _ := os.Stat(path)
	if !info1.ModTime().Equal(info2.ModTime()) || !s.Status().LastWrite.Equal(firstWrite) {
		t.Error("file should not be rewritten when the content is unchanged")
	}
	if st := s.Status(); st.Endpoints != 1 || st.LastError != "" {
		t.Errorf("unexpected status %+v", st)
	}
}

func TestTouchIfUnchanged(t *testing.T) {
	path := filepath.Join(t.TempDir(), "f.yaml")
	_ = os.WriteFile(path, []byte("a"), 0o644)
	old := time.Now().Add(-time.Hour)
	_ = os.Chtimes(path, old, old)
	touchIfUnchanged(path, []byte("b"))
	if info, _ := os.Stat(path); !info.ModTime().Equal(old) {
		t.Error("a file with different content must not be touched")
	}
	touchIfUnchanged(path, []byte("a"))
	if info, _ := os.Stat(path); time.Since(info.ModTime()) > time.Minute {
		t.Error("expected the modification time to be updated")
	}
}

