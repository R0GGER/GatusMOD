func TestBuild(t *testing.T) {
	records := []store.Record{
		{ID: "1", Name: "web", Group: "core", URL: "https://example.org", Method: "get", Conditions: "[STATUS] == 200\n\n# comment\n- \"[RESPONSE_TIME] < 500\"\n"},
		{ID: "2", Name: "api", Group: "core", URL: "https://api.example.org", Interval: "30s", Disabled: true, Conditions: "[STATUS] == 200",
			Extra: "headers:\n  X-Test: \"1\"\nalerts:\n  - type: slack\nname: ignored\n"},
		{ID: "3", Name: "no-url", Conditions: "[STATUS] == 200"},
		{ID: "4", Name: "bad-interval", URL: "https://x", Interval: "soon", Conditions: "[STATUS] == 200"},
		{ID: "5", Name: "no-conditions", URL: "https://x"},
		{ID: "6", Name: "web", Group: "core", URL: "https://dup", Conditions: "[STATUS] == 200"},
		{ID: "7", Name: "bad-extra", URL: "https://x", Conditions: "[STATUS] == 200", Extra: "- not a map"},
		{ID: "8", Name: "cond-in-extra", URL: "https://x", Extra: "conditions:\n  - \"[CONNECTED] == true\"\n"},
	}
	data, count, problems := Build(records, "2m")
	if count != 3 {
		t.Errorf("expected 3 endpoints, got %d\n%s", count, data)
	}
	if len(problems) != 5 {
		t.Errorf("expected 5 problems, got %v", problems)
	}
	var parsed struct {
		Endpoints []map[string]any `yaml:"endpoints"`
	}
	if err := yaml.Unmarshal(data, &parsed); err != nil {
		t.Fatalf("output is not valid YAML: %v\n%s", err, data)
	}
	byName := map[string]map[string]any{}
	for _, ep := range parsed.Endpoints {
		byName[ep["name"].(string)] = ep
	}
	api := byName["api"]
	if api["interval"] != "30s" || api["enabled"] != false || api["headers"] == nil || api["alerts"] == nil {
		t.Errorf("unexpected api endpoint %+v", api)
	}
	web := byName["web"]
	if web["interval"] != "2m" || web["method"] != "GET" || web["url"] != "https://example.org" {
		t.Errorf("unexpected web endpoint %+v", web)
	}
	if c := web["conditions"].([]any); len(c) != 2 || c[1] != "[RESPONSE_TIME] < 500" {
		t.Errorf("unexpected conditions %v", c)
	}
	if _, ok := web["enabled"]; ok {
		t.Error("enabled endpoints should not have an explicit enabled key")
	}
	if byName["cond-in-extra"]["conditions"] == nil {
		t.Error("conditions from extra should be used when the column is empty")
	}
	if !strings.HasPrefix(string(data), "# Generated by GatusMOD") {
		t.Error("expected generated header")
	}
}

func TestBuild_ExternalEndpoints(t *testing.T) {
	records := []store.Record{
		{Name: "web", Group: "core", URL: "https://example.org", Conditions: "[STATUS] == 200"},
		{Name: "speed", Group: "iperf", URL: "iperf3://speed.example.org:5201", Interval: "5m", Conditions: "[STATE] == ready",
			Extra: "alerts:\n  - type: slack\nheaders:\n  X-Ignored: \"1\"\n"},
		{Name: "db", Group: "core", URL: "postgres://app:s3cret@db/app", Conditions: "[CONNECTED] == true"},
		{Name: "backup", Group: "jobs", URL: "push://", Interval: "24h"},
		{Name: "web", Group: "core", URL: "ntp://pool.ntp.org", Conditions: "[CONNECTED] == true"},
		{Name: "bad", URL: "ntp://pool.ntp.org", Conditions: "[STATUS] == 200"},
		{Name: "off", URL: "smtp://mx.example.org", Conditions: "[CODE] == 220", Disabled: true},
	}
	data, kept, problems := build(records, "1m", "tok")
	if len(kept) != 5 || len(problems) != 2 {
		t.Fatalf("expected 5 endpoints and 2 problems, got %d %v\n%s", len(kept), problems, data)
	}
	if strings.Contains(string(data), "s3cret") || strings.Contains(string(data), "iperf3://") {
		t.Errorf("probe URLs must not be written for Gatus:\n%s", data)
	}
	var parsed struct {
		Endpoints         []map[string]any `yaml:"endpoints"`
		ExternalEndpoints []map[string]any `yaml:"external-endpoints"`
	}
	if err := yaml.Unmarshal(data, &parsed); err != nil {
		t.Fatalf("output is not valid YAML: %v\n%s", err, data)
	}
	if len(parsed.Endpoints) != 1 || len(parsed.ExternalEndpoints) != 4 {
		t.Fatalf("expected 1 endpoint and 4 external endpoints:\n%s", data)
	}
	byName := map[string]map[string]any{}
	for _, ep := range parsed.ExternalEndpoints {
		byName[ep["name"].(string)] = ep
		if ep["token"] != "tok" || ep["url"] != nil || ep["conditions"] != nil || ep["interval"] != nil {
			t.Errorf("unexpected external endpoint %+v", ep)
		}
	}
	speed := byName["speed"]
	if speed["heartbeat"].(map[string]any)["interval"] != "10m0s" || speed["alerts"] == nil || speed["headers"] != nil {
		t.Errorf("unexpected iperf3 endpoint %+v", speed)
	}
	if byName["backup"]["heartbeat"].(map[string]any)["interval"] != "24h0m0s" {
		t.Errorf("push heartbeat should be the interval: %+v", byName["backup"])
	}
	if byName["off"]["enabled"] != false {
		t.Errorf("disabled probe should be disabled in Gatus: %+v", byName["off"])
	}

	targets := Targets(kept)
	if len(targets) != 3 {
		t.Fatalf("expected 3 targets (the disabled one is skipped), got %+v", targets)
	}
	for _, tg := range targets {
		if tg.Key == "iperf_speed" && (tg.Interval != 5*time.Minute || tg.Conditions[0] != "[STATE] == ready") {
			t.Errorf("unexpected target %+v", tg)
		}
		if tg.Key == "core_db" && tg.Interval != time.Minute {
			t.Errorf("the default interval should apply: %+v", tg)
		}
	}
}

