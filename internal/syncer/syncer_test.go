func TestWrite_FilePerImport(t *testing.T) {
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		_, _ = w.Write([]byte(`{"list":[{"Id":1,"name":"same","url":"https://same.example.org","conditions":"[STATUS] == 200"}],"pageInfo":{"isLastPage":true}}`))
	}))
	defer srv.Close()
	dir := t.TempDir()
	shared := filepath.Join(dir, config.DefaultOutputFile)
	_ = os.WriteFile(shared, []byte("endpoints: [old]\n"), 0o644)
	orphan := filepath.Join(dir, "zz-gatusmod-gone.yaml")
	_ = os.WriteFile(orphan, []byte("# Generated by GatusMOD for Gone:x (import gone). Do not edit.\nendpoints: []\n"), 0o644)
	imp := func(id, name, table string) config.Import {
		return config.Import{ID: id, Name: name, DatabaseID: "db", DatabaseName: "NocoDB-prod", Provider: "nocodb", URL: srv.URL,
			TableID: table, Type: config.TypeCustom, Fields: config.Fields{Name: "name", URL: "url", Conditions: "conditions"}}
	}
	cfg := &config.Config{Path: dir, Imports: []config.Import{imp("a", "http-sites", "a"), imp("b", "other", "b")}}
	s := New(func() *config.Config { return cfg })
	if err := s.SyncOnce(context.Background()); err != nil {
		t.Fatal(err)
	}
	a := filepath.Join(dir, "zz-gatusmod-nocodb-prod-http-sites.yaml")
	b := filepath.Join(dir, "zz-gatusmod-nocodb-prod-other.yaml")
	dataA, _ := os.ReadFile(a)
	dataB, _ := os.ReadFile(b)
	if !strings.HasPrefix(string(dataA), "# Generated by GatusMOD for NocoDB-prod:http-sites (import a).") || !strings.Contains(string(dataA), "same.example.org") {
		t.Errorf("unexpected file of http-sites\n%s", dataA)
	}
	if strings.Contains(string(dataB), "same.example.org") || len(s.Status().Problems) != 1 {
		t.Errorf("a duplicate in another file must be skipped\n%s\n%+v", dataB, s.Status().Problems)
	}
	if data, _ := os.ReadFile(shared); strings.Contains(string(data), "old") {
		t.Error("the endpoints of the database imports must move out of the shared file")
	}
	if _, err := os.Stat(orphan); err != nil {
		t.Error("an orphaned file must not be removed automatically")
	}
	if got := OrphanedFiles(cfg); len(got) != 1 || got[0].ImportID != "gone" {
		t.Errorf("unexpected orphans %+v", got)
	}

	cfg.Imports[0].Name = "renamed"
	if err := s.SyncOnce(context.Background()); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(a); !errors.Is(err, os.ErrNotExist) {
		t.Error("the file of a renamed import must be removed")
	}
	if _, err := os.Stat(filepath.Join(dir, "zz-gatusmod-nocodb-prod-renamed.yaml")); err != nil {
		t.Error("the renamed import needs its new file")
	}

	removed, err := s.RemoveFiles(cfg, "b")
	if err != nil || len(removed) != 1 || removed[0] != "zz-gatusmod-nocodb-prod-other.yaml" {
		t.Errorf("unexpected removal %v %v", removed, err)
	}
}

