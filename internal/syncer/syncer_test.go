func TestRunImport_CombinesImports(t *testing.T) {
	var failB bool
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		switch {
		case strings.Contains(r.URL.Path, "/tables/a/"):
			if r.URL.Query().Get("viewId") != "v" {
				t.Errorf("expected the view id, got %s", r.URL.RawQuery)
			}
			_, _ = w.Write([]byte(`{"list":[{"Id":1,"host":"a.example.org","port":"5201-5205"},{"Id":2,"host":""}],"pageInfo":{"isLastPage":true}}`))
		case failB:
			w.WriteHeader(http.StatusBadGateway)
		default:
			_, _ = w.Write([]byte(`{"list":[{"Id":1,"name":"site","url":"https://b.example.org"}],"pageInfo":{"isLastPage":true}}`))
		}
	}))
	defer srv.Close()
	dir := t.TempDir()
	cfg := &config.Config{Path: dir, Imports: []config.Import{
		{ID: "a", Name: "servers", Group: "iperf", Provider: "nocodb", URL: srv.URL, TableID: "a", ViewID: "v", Type: config.TypeTCP,
			Fields: config.Fields{Host: "host", Port: "port"}, Interval: "15m"},
		{ID: "b", Name: "sites", Provider: "nocodb", URL: srv.URL, TableID: "b", Type: config.TypeCustom, Fields: config.Fields{Name: "name", URL: "url"}},
	}}
	s := New(func() *config.Config { return cfg })
	if err := s.RunImport(context.Background(), "a", TriggerManual); err != nil {
		t.Fatal(err)
	}
	servers, _ := os.ReadFile(filepath.Join(dir, "zz-gatusmod-servers.yaml"))
	for _, want := range []string{"(import a)", "name: a.example.org", "group: iperf", "url: tcp://a.example.org:5201", "interval: 15m", "[CONNECTED] == true"} {
		if !strings.Contains(string(servers), want) {
			t.Errorf("the file of servers should contain %q\n%s", want, servers)
		}
	}
	if sites, _ := os.ReadFile(filepath.Join(dir, "zz-gatusmod-sites.yaml")); !strings.Contains(string(sites), "url: https://b.example.org") || strings.Contains(string(sites), "a.example.org") {
		t.Errorf("every import should have its own file\n%s", sites)
	}
	if shared, _ := os.ReadFile(filepath.Join(dir, config.DefaultOutputFile)); !strings.Contains(string(shared), "endpoints: []") {
		t.Errorf("the file of the local tables should be empty\n%s", shared)
	}
	st := s.Status()
	if st.Imports["a"].Endpoints != 1 || st.Imports["a"].Rows != 2 || st.Imports["b"].Endpoints != 1 || len(st.Problems) != 1 {
		t.Errorf("unexpected status %+v", st)
	}
	if recs := s.Records(); len(recs) != 2 || recs[0].Source == "" {
		t.Errorf("unexpected records %+v", recs)
	}

	// A failing import keeps its last rows, so its endpoints stay in the file.
	failB = true
	if err := s.RunImport(context.Background(), "b", TriggerManual); err == nil {
		t.Error("expected an error")
	}
	if data, _ := os.ReadFile(filepath.Join(dir, "zz-gatusmod-sites.yaml")); !strings.Contains(string(data), "b.example.org") {
		t.Error("the endpoints of a failing import must be kept")
	}
	if err := s.RunImport(context.Background(), "nope", TriggerManual); err != ErrUnknownImport {
		t.Errorf("expected ErrUnknownImport, got %v", err)
	}
}

