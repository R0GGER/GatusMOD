package config

import (
	"errors"
	"os"
	"path/filepath"
	"testing"
	"time"
)

func writeFile(t *testing.T, dir, name, content string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestLoad_FromDirectory(t *testing.T) {
	dir := t.TempDir()
	t.Setenv("GM_TEST_TOKEN", "secret")
	writeFile(t, dir, "config.yaml", `
endpoints:
  - name: x
    url: https://example.org
    conditions: ["[STATUS] == 200"]
gatusmod:
  base-url: https://status.example.com/
  defaults:
    interval: 2m
  ui:
    items-per-page: 48
    dashboard-heading-show: false
  database:
    provider: NocoDB
    url: http://nocodb:8080
    token: ${GM_TEST_TOKEN}
    table-id: abc
`)
	writeFile(t, dir, "other.yml", "endpoints: []\n")
	writeFile(t, dir, DefaultOutputFile, "gatusmod: {}\n")
	writeFile(t, dir, "zz-gatusmod-nocodb-sites.yaml", "# Generated by GatusMOD for NocoDB:sites (import a1). Do not edit.\ngatusmod: {}\n")
	cfg, err := Load(dir)
	if err != nil {
		t.Fatal(err)
	}
	if cfg.Upstream != DefaultUpstream || cfg.Listen != DefaultListen {
		t.Errorf("defaults not applied: %+v", cfg)
	}
	if cfg.Database.Token != "secret" || cfg.Database.Provider != "nocodb" || cfg.Database.SyncInterval != time.Minute {
		t.Errorf("database not parsed correctly: %+v", cfg.Database)
	}
	if cfg.UI.HeadingVisible() || !cfg.UI.SubtitleVisible() {
		t.Error("heading should be hidden and subtitle visible")
	}
	if got := cfg.ResolveURL("[baseurl]/images/a.png"); got != "https://status.example.com/images/a.png" {
		t.Errorf("unexpected resolved url %s", got)
	}
	out, err := cfg.OutputPath()
	if err != nil || out != filepath.Join(dir, DefaultOutputFile) {
		t.Errorf("unexpected output path %s (%v)", out, err)
	}
}

func TestLoad_Errors(t *testing.T) {
	cases := map[string]struct {
		content string
		want    error
	}{
		"missing":   {"endpoints: []\n", ErrNoConfig},
		"provider":  {"gatusmod:\n  database:\n    provider: mysql\n", ErrInvalidProvider},
		"table":     {"gatusmod:\n  database:\n    provider: baserow\n    url: http://x\n", ErrMissingTableID},
		"analytics": {"gatusmod:\n  analytics:\n    provider: ga\n", ErrInvalidAnalytics},
		"admin":     {"gatusmod:\n  admin:\n    username: admin\n", ErrInvalidAdmin},
		"time":      {"gatusmod:\n  ui:\n    time-format: 13h\n", ErrInvalidTimeFormat},
		"date":      {"gatusmod:\n  ui:\n    date-format: YYYY-MM-DD\n", ErrInvalidDateFormat},
	}
	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			writeFile(t, dir, "config.yaml", tc.content)
			if _, err := Load(dir); !errors.Is(err, tc.want) {
				t.Errorf("expected %v, got %v", tc.want, err)
			}
		})
	}
}

func TestLoad_MultipleBlocks(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, dir, "a.yaml", "gatusmod: {}\n")
	writeFile(t, dir, "b.yaml", "gatusmod: {}\n")
	if _, err := Load(dir); !errors.Is(err, ErrMultipleConfigs) {
		t.Errorf("expected ErrMultipleConfigs, got %v", err)
	}
}

