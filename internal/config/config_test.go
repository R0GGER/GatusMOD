func TestOutputPath_FileConfig(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, dir, "config.yaml", "gatusmod:\n  database:\n    provider: nocodb\n    url: http://x\n    table-id: t\n")
	cfg, err := Load(filepath.Join(dir, "config.yaml"))
	if err != nil {
		t.Fatal(err)
	}
	if _, err := cfg.OutputPath(); err == nil {
		t.Error("expected an error when the config path is a file and output-file is relative")
	}
}
