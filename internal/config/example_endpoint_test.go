package config

import (
	"errors"
	"os"
	"path/filepath"
	"testing"
)

const exampleConfig = `storage:
  type: sqlite

ui:
  title: Status

# Gatus does not start without at least one endpoint.
# Remove it on the Settings page.
endpoints:
  - name: GatusMOD
    group: Monitoring
    url: http://gatusmod:8080/mod/health
    interval: 1m
    conditions:
      - "[STATUS] == 200"

gatusmod:
  admin:
    password-bcrypt: "$$2a$$10$$abc"
`

func TestRemoveExampleEndpoint_OnlyEndpoint(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, dir, "config.yaml", exampleConfig)

	ex, err := FindExampleEndpoint(dir)
	if err != nil || ex == nil || ex.Label() != "Monitoring/GatusMOD" || ex.OtherEndpoints != 0 {
		t.Fatalf("unexpected example %+v (%v)", ex, err)
	}
	if _, err := RemoveExampleEndpoint(dir); !errors.Is(err, ErrLastEndpoint) {
		t.Fatalf("the last endpoint must not be removed, got %v", err)
	}

	writeFile(t, dir, DefaultOutputFile, "# Generated by GatusMOD\nendpoints:\n  - name: placeholder\n    enabled: false\n")
	if _, err := RemoveExampleEndpoint(dir); err != nil {
		t.Fatal(err)
	}
	want := `storage:
  type: sqlite

ui:
  title: Status

gatusmod:
  admin:
    password-bcrypt: "$$2a$$10$$abc"
`
	if data, _ := os.ReadFile(filepath.Join(dir, "config.yaml")); string(data) != want {
		t.Errorf("unexpected file\n%s", data)
	}
	if ex, err := FindExampleEndpoint(dir); err != nil || ex != nil {
		t.Errorf("the example should be gone: %+v %v", ex, err)
	}
	if _, err := RemoveExampleEndpoint(dir); !errors.Is(err, ErrNoExampleEndpoint) {
		t.Errorf("expected ErrNoExampleEndpoint, got %v", err)
	}
}

func TestRemoveExampleEndpoint_KeepsOtherEndpoints(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, dir, "config.yaml", "endpoints:\r\n"+
		"  - name: mine\r\n    url: https://example.org\r\n    conditions: [\"[STATUS] == 200\"]\r\n"+
		"  # the example\r\n"+
		"  - name: GatusMOD\r\n    url: http://gatusmod:8080/mod/health\r\n    conditions:\r\n      - \"[STATUS] == 200\"\r\n"+
		"  # keep this comment\r\n"+
		"  - name: other\r\n    url: https://other.example.org\r\n    conditions: [\"[STATUS] == 200\"]\r\n"+
		"gatusmod: {}\r\n")

	ex, err := RemoveExampleEndpoint(dir)
	if err != nil || ex.OtherEndpoints != 2 {
		t.Fatalf("unexpected result %+v (%v)", ex, err)
	}
	want := "endpoints:\r\n" +
		"  - name: mine\r\n    url: https://example.org\r\n    conditions: [\"[STATUS] == 200\"]\r\n" +
		"  # keep this comment\r\n" +
		"  - name: other\r\n    url: https://other.example.org\r\n    conditions: [\"[STATUS] == 200\"]\r\n" +
		"gatusmod: {}\r\n"
	if data, _ := os.ReadFile(filepath.Join(dir, "config.yaml")); string(data) != want {
		t.Errorf("unexpected file\n%q", data)
	}
	if _, err := Load(dir); err != nil {
		t.Errorf("the configuration no longer loads: %v", err)
	}
}

func TestRemoveExampleEndpoint_FlowStyle(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, dir, "config.yaml", "endpoints: [{name: GatusMOD, url: 'http://gatusmod:8080/mod/health'}, {name: x, url: 'https://x'}]\ngatusmod: {}\n")
	if _, err := RemoveExampleEndpoint(dir); err == nil {
		t.Error("a flow-style list must not be edited")
	}
}
