func TestImport_Validate(t *testing.T) {
	valid := Import{Name: "a", Provider: "baserow", URL: "https://b", TableID: "1", Type: TypeTCP}
	cases := map[string]struct {
		change func(*Import)
		want   string
	}{
		"valid":         {func(*Import) {}, ""},
		"no name":       {func(i *Import) { i.Name = " " }, ErrMissingImportName.Error()},
		"provider":      {func(i *Import) { i.Provider = "airtable" }, ErrInvalidProvider.Error()},
		"no table":      {func(i *Import) { i.TableID = "" }, ErrMissingImportTable.Error()},
		"type":          {func(i *Import) { i.Type = "ftp" }, ErrInvalidImportType.Error()},
		"custom no url": {func(i *Import) { i.Type = TypeCustom }, ErrCustomNeedsURL.Error()},
		"interval":      {func(i *Import) { i.Interval = "-1m" }, "not a valid positive duration"},
		"cron":          {func(i *Import) { i.ManualSchedule, i.Cron = true, "every day" }, "cron"},
		"cron ok":       {func(i *Import) { i.ManualSchedule, i.Cron = true, "*/30 * * * *" }, ""},
		"manual only":   {func(i *Import) { i.ManualSchedule = true }, ""},
	}
	for name, tc := range cases {
		t.Run(name, func(t *testing.T) {
			imp := valid
			tc.change(&imp)
			err := imp.Validate()
			if tc.want == "" && err != nil || tc.want != "" && (err == nil || !strings.Contains(err.Error(), tc.want)) {
				t.Errorf("got %v, want %q", err, tc.want)
			}
		})
	}
}

func TestImport_NextRun(t *testing.T) {
	now := time.Date(2026, 10, 12, 22, 15, 4, 0, time.UTC)
	imp := Import{Interval: "15m"}
	if got := imp.NextRun("", now); !got.Equal(time.Date(2026, 10, 12, 22, 30, 0, 0, time.UTC)) {
		t.Errorf("interval schedule should be aligned to the clock, got %v", got)
	}
	cest := time.FixedZone("CEST", 2*3600)
	if got := (&Import{Interval: "1h"}).NextRun("", now.In(cest)); got.In(cest).Minute() != 0 || got.In(cest).Hour() != 1 {
		t.Errorf("hourly schedule should be aligned to the local hour, got %v", got.In(cest))
	}
	if got := (&Import{}).NextRun("2m", now); !got.Equal(time.Date(2026, 10, 12, 22, 16, 0, 0, time.UTC)) {
		t.Errorf("defaults.interval should be used, got %v", got)
	}
	cron := Import{ManualSchedule: true, Cron: "0 * * * *"}
	if got := cron.NextRun("", now); !got.Equal(time.Date(2026, 10, 12, 23, 0, 0, 0, time.UTC)) {
		t.Errorf("unexpected cron run %v", got)
	}
	if got := (&Import{ManualSchedule: true}).NextRun("", now); !got.IsZero() {
		t.Errorf("manual-only imports have no next run, got %v", got)
	}
	if s := imp.ScheduleText(""); s != "Every 15m" {
		t.Errorf("unexpected schedule text %q", s)
	}
}

func TestFromDatabase(t *testing.T) {
	imp := FromDatabase(&Database{Provider: "nocodb", URL: "u", TableID: "t", SyncInterval: time.Minute})
	if err := imp.Validate(); err != nil {
		t.Fatal(err)
	}
	if imp.Cron != "@every 1m0s" || imp.Fields != LegacyFields {
		t.Errorf("unexpected import %+v", imp)
	}
	if !errors.Is((&Config{Imports: []Import{{}}}).Validate(), ErrMissingImportName) {
		t.Error("Config.Validate should validate the imports")
	}
}

func TestImport_FileName(t *testing.T) {
	imp := Import{ID: "abc", Name: "http sites", DatabaseName: "NocoDB-prod", Provider: "nocodb"}
	if imp.Label() != "NocoDB-prod:http sites" || imp.FileName() != "zz-gatusmod-nocodb-prod-http-sites.yaml" {
		t.Errorf("unexpected label %q or file %q", imp.Label(), imp.FileName())
	}
	if id, ok := ImportIDFromHeader(imp.FileHeader()); !ok || id != "abc" {
		t.Errorf("the header should give the import ID back, got %q %v", id, ok)
	}
	if _, ok := ImportIDFromHeader("# Generated by GatusMOD from the central database."); ok {
		t.Error("the header of the local tables file is not an import header")
	}
	if got := (&Import{ID: "x9", Name: ":::"}).FileName(); got != "zz-gatusmod-x9.yaml" {
		t.Errorf("an empty slug should fall back to the ID, got %q", got)
	}
}

func TestConfig_ValidateImportFiles(t *testing.T) {
	imp := func(id, db, name string) Import {
		return Import{ID: id, Name: name, DatabaseID: "d", DatabaseName: db, Provider: "nocodb", URL: "u", TableID: "t", Type: TypeHTTP}
	}
	cfg := &Config{Imports: []Import{imp("a", "NocoDB", "a b"), imp("b", "NocoDB", "a-b")}}
	if err := cfg.Validate(); err == nil || !strings.Contains(err.Error(), "zz-gatusmod-nocodb-a-b.yaml") {
		t.Errorf("two imports writing the same file must be rejected, got %v", err)
	}
	cfg = &Config{Imports: []Import{{ID: "a", Name: "endpoints", Provider: "nocodb", URL: "u", TableID: "t", Type: TypeHTTP}}}
	if err := cfg.Validate(); err == nil {
		t.Error("an import must not write the file of the local tables")
	}
}
